from fastapi import APIRouter, HTTPException, status, Depends, Path
from typing import List
import uuid

from app.core import get_supabase_client, AuthenticatedUser, get_current_authenticated_doctor # Updated imports
from supabase import Client

from app.models.user import MedicalInfoDB, MedicalInfoCreate # MedicalInfoUpdate is defined but not used yet

router = APIRouter(
    prefix="/doctors",
    tags=["doctors"]
)

